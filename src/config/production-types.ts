const getFlatProductionTypes = (categories: ProductionTypeCategory[]): string[] => {
  const allTypes = new Set<string>();
  categories.forEach(cat => cat.subcategories.forEach(sub => sub.items.forEach(item => allTypes.add(item))));
  return Array.from(allTypes).sort((a,b) => a.localeCompare(b, 'el'));
}

